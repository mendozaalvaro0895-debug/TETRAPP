select count(*) as lineas, count(distinct fecha) as dias, min(fecha) as desde,
       max(fecha) as hasta, to_char(sum(cantidad),'FM999,999,999') as unidades
from public.produccion_diaria where documento = 'SHEETS';

select count(*) filter (where meta_12hrs is not null)              as con_meta,
       count(*) filter (where maquina_default is not null)         as con_maquina,
       count(*) filter (where precio_ponderado_manual is not null) as con_precio
from public.inventario;

-- SKUs producidos que NO existen en inventario (se quedan sin meta ni precio)
select p.sku, max(p.descripcion) as descripcion,
       to_char(sum(p.cantidad),'FM999,999,999') as unidades
from public.produccion_diaria p left join public.inventario i on i.sku = p.sku
where i.sku is null group by p.sku order by sum(p.cantidad) desc;
